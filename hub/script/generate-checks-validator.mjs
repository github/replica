import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import Ajv from "ajv"
import standaloneCode from "ajv/dist/standalone/index.js"
import { build } from "vite"

const directory = new URL(
  "../../.github/extensions/replica-prototype/checks-config/",
  import.meta.url,
)
const schemaSource = await readFile(new URL("schema.v2.json", directory), "utf8")
const schema = JSON.parse(schemaSource)
const ajv = new Ajv({ allErrors: true, strict: true, strictTypes: false, code: { source: true } })
const temporary = await mkdtemp(join(tmpdir(), "replica-checks-validator-"))
const require = createRequire(import.meta.url)
const check = process.argv.includes("--check")

async function bundle(entry) {
  const result = await build({
    configFile: false,
    publicDir: false,
    logLevel: "silent",
    resolve: { alias: { ajv: dirname(require.resolve("ajv/package.json")) } },
    build: {
      write: false,
      target: "node24",
      minify: true,
      lib: { entry, formats: ["cjs"], fileName: "validator" },
      rollupOptions: { external: (id) => id.startsWith("node:") },
    },
  })
  const output = (Array.isArray(result) ? result[0] : result).output.find(
    (item) => item.type === "chunk",
  )
  if (!output) throw new Error("Checks validator bundling produced no JavaScript.")
  return (
    "// Generated by npm run checks:schema:generate in hub/. Do not edit.\n/* eslint-disable */\n" +
    output.code
  )
}

async function save(url, source) {
  if (check) {
    if ((await readFile(url, "utf8")) !== source)
      throw new Error(
        `Checks schema artifacts are stale: ${url.pathname}. Run npm run checks:schema:generate in hub/.`,
      )
  } else {
    await writeFile(url, source)
  }
}

try {
  const entry = join(temporary, "shape.cjs")
  await writeFile(entry, standaloneCode(ajv, ajv.compile(schema)))
  await save(new URL("shape.cjs", directory), await bundle(entry))
} finally {
  await rm(temporary, { recursive: true, force: true })
}
