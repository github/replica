# Creates a reviewable pull request that synchronizes the fixed Replica workflow.
class Repository::WorkflowInstallation < ActiveRecord::AssociatedObject
  WORKFLOW_PATH = ".github/workflows/replica.yml"
  BRANCH_NAME = Repository::RESERVED_BRANCHES.fetch(0)
  INSTALL_COMMIT_MESSAGE = "feat: add Replica workflow"
  INSTALL_PULL_REQUEST_TITLE = "Add Replica workflow"
  INSTALL_PULL_REQUEST_BODY = \
    "Adds the workflow Replica Hub uses to build and review prototype branches."
  UPDATE_COMMIT_MESSAGE = "chore: update Replica workflow"
  UPDATE_PULL_REQUEST_TITLE = "Update Replica workflow"
  UPDATE_PULL_REQUEST_BODY = \
    "Synchronizes the repository workflow with the version generated by Replica Hub."

  class AlreadyInstalled < StandardError; end
  class BranchConflict < StandardError; end

  # Offers updates for old Action pins and the generated default-branch exclusion.
  def status(configuration: GithubAppConfiguration.current)
    raise LocalDevelopment::Error, "GitHub workflow installation is disabled in local mode" if LocalDevelopment.enabled?

    client = configuration.github_client
    workflow_file(client, configuration.tokens.installation, ref: record.default_branch).fetch(:state)
  end

  # Creates or reuses a safe synchronization branch and returns its open pull request.
  def create_pull_request!(configuration: GithubAppConfiguration.current)
    raise LocalDevelopment::Error, "GitHub workflow installation is disabled in local mode" if LocalDevelopment.enabled?

    raise ArgumentError, "Replica build action is not configured" if build_action.blank?
    raise BranchConflict if record.default_branch == BRANCH_NAME

    client = configuration.github_client
    token = configuration.tokens.installation
    default_workflow = workflow_file(client, token, ref: record.default_branch)
    raise AlreadyInstalled if [ :current, :present ].include?(default_workflow.fetch(:state))

    default_sha = reference_sha \
      client.repositories.reference(record, record.default_branch, token:)
    prepare_branch!(client, token, default_sha, default_workflow)
    pull_request = existing_pull_request(client, token)
    pull_request ||= client.pull_requests.create \
      record,
      head: BRANCH_NAME,
      base: record.default_branch,
      title: pull_request_title(default_workflow),
      body: pull_request_body(default_workflow),
      token: token
    validate_pull_request!(pull_request)
  end

  private

  # Returns the configured action reference used by every generated workflow.
  def build_action
    Rails.configuration.x.build_action.to_s
  end

  # Builds the complete workflow committed to the prototype repository.
  def workflow
    <<~YAML
      name: Replica

      on:
        push:

      permissions:
        contents: read

      concurrency:
        group: replica-${{ github.repository_id }}-${{ github.ref }}
        cancel-in-progress: false

      jobs:
        build:
          if: github.ref_name != 'replica/install-workflow'
          runs-on: ubuntu-latest
          timeout-minutes: 15
          steps:
            - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1
              with:
                ref: ${{ github.sha }}
                persist-credentials: false
            - uses: #{build_action}
    YAML
  end

  # Creates the synchronization branch or proves a prior attempt prepared it safely.
  def prepare_branch!(client, token, default_sha, default_workflow)
    branch = branch_reference(client, token)
    if branch.nil?
      client.repositories.create_reference(record, BRANCH_NAME, default_sha, token:)
      synchronize_workflow!(client, token, default_workflow)
      return validate_prepared_branch!(client, token, default_sha, default_workflow)
    end

    if reference_sha(branch) == default_sha
      synchronize_workflow!(client, token, default_workflow)
    end

    validate_prepared_branch!(client, token, default_sha, default_workflow)
  end

  # Creates or updates the workflow on a branch copied from the current default.
  def synchronize_workflow!(client, token, default_workflow)
    case default_workflow.fetch(:state)
    when :missing
      create_workflow!(client, token)
    when :different
      update_workflow!(client, token, default_workflow.fetch(:sha))
    else
      raise GithubClient::InvalidResponse, "Replica workflow has an invalid synchronization state"
    end
  end

  # Proves the branch contains only the workflow change Hub intends to propose.
  def validate_prepared_branch!(client, token, default_sha, default_workflow)
    branch = branch_reference(client, token)
    raise GithubClient::InvalidResponse, "GitHub did not return the workflow branch" if branch.nil?
    raise BranchConflict if workflow_file(client, token, ref: BRANCH_NAME).fetch(:state) != :current

    comparison = client.repositories.compare \
      record,
      record.default_branch,
      BRANCH_NAME,
      token: token
    validate_comparison! \
      comparison,
      default_sha: default_sha,
      branch_sha: reference_sha(branch),
      file_status: expected_file_status(default_workflow)
  end

  # Rejects comparisons that include stale, missing, or unrelated repository changes.
  def validate_comparison!(payload, default_sha:, branch_sha:, file_status:)
    merge_base_sha = payload.fetch("merge_base_commit").fetch("sha")
    commits = payload.fetch("commits")
    files = payload.fetch("files")
    valid = payload.fetch("status") == "ahead" &&
      payload.fetch("ahead_by") == 1 &&
      payload.fetch("behind_by") == 0 &&
      payload.fetch("total_commits") == 1 &&
      merge_base_sha == default_sha &&
      commits.is_a?(Array) &&
      commits.one? &&
      commits.first.is_a?(Hash) &&
      commits.first.fetch("sha") == branch_sha &&
      files.is_a?(Array) &&
      files.one? &&
      files.first.is_a?(Hash) &&
      files.first.fetch("filename") == WORKFLOW_PATH &&
      files.first.fetch("status") == file_status
    raise BranchConflict if !valid

    payload
  rescue KeyError, TypeError
    raise GithubClient::InvalidResponse, "GitHub returned an incomplete branch comparison"
  end

  # Returns the existing synchronization branch or nil when no prior attempt created it.
  def branch_reference(client, token)
    client.repositories.reference(record, BRANCH_NAME, token:)
  rescue GithubClient::NotFound
    nil
  end

  # Creates the workflow file on the installation branch.
  def create_workflow!(client, token)
    client.repositories.create_file \
      record,
      WORKFLOW_PATH,
      workflow,
      branch: BRANCH_NAME,
      message: INSTALL_COMMIT_MESSAGE,
      token: token
  end

  # Replaces the differing workflow while preserving review through a pull request.
  def update_workflow!(client, token, sha)
    client.repositories.update_file \
      record,
      WORKFLOW_PATH,
      workflow,
      sha: sha,
      branch: BRANCH_NAME,
      message: UPDATE_COMMIT_MESSAGE,
      token: token
  end

  # Returns the workflow state and identity at one branch.
  def workflow_file(client, token, ref:)
    payload = client.repositories.content \
      record,
      WORKFLOW_PATH,
      ref: ref,
      token: token
    content = Base64.strict_decode64(payload.fetch("content").delete("\n"))
    return { state: :present, sha: nil } if build_action.blank?

    state = workflow_state(content)
    sha = state == :different ? content_sha(payload) : nil
    { state: state, sha: sha }
  rescue GithubClient::NotFound
    { state: :missing, sha: nil }
  rescue KeyError, TypeError, ArgumentError
    raise GithubClient::InvalidResponse, "GitHub returned invalid workflow contents"
  end

  # Recognizes the old generated branch guard without replacing custom workflows.
  def workflow_state(content)
    return :current if content == workflow
    legacy_workflow = workflow.sub \
      "if: github.ref_name != 'replica/install-workflow'",
      "if: github.ref_name != github.event.repository.default_branch && github.ref_name != 'replica/install-workflow'"
    return :different if content == legacy_workflow

    action_path, current_revision = build_action.split("@", 2)
    action_pattern = \
      /^[ \t]*-[ \t]+uses:[ \t]*["']?#{Regexp.escape(action_path)}@([0-9a-fA-F]{40})["']?(?:[ \t]+#.*)?[ \t]*$/
    installed_revisions = content.scan(action_pattern).flatten
    return :present if installed_revisions.empty?

    current_revisions = Rails.configuration.x.build_action_revisions
    return :current if installed_revisions.all? { _1.casecmp?(current_revision) }
    known_revision = current_revisions.nil? ||
      installed_revisions.any? { current_revisions.include?(_1.downcase) }
    if known_revision && installed_revisions.uniq.one?
      previous_generated = workflow.sub(build_action, "#{action_path}@#{installed_revisions.first}")
      previous_legacy = previous_generated.sub \
        "if: github.ref_name != 'replica/install-workflow'",
        "if: github.ref_name != github.event.repository.default_branch && github.ref_name != 'replica/install-workflow'"
      return :different if content == previous_generated || content == previous_legacy
    end

    :present
  end

  # Returns the expected GitHub file status for the proposed synchronization.
  def expected_file_status(default_workflow)
    default_workflow.fetch(:state) == :missing ? "added" : "modified"
  end

  # Returns the commit message appropriate for the proposed synchronization.
  def pull_request_title(default_workflow)
    default_workflow.fetch(:state) == :missing ? INSTALL_PULL_REQUEST_TITLE : UPDATE_PULL_REQUEST_TITLE
  end

  # Returns the pull request explanation appropriate for the synchronization.
  def pull_request_body(default_workflow)
    default_workflow.fetch(:state) == :missing ? INSTALL_PULL_REQUEST_BODY : UPDATE_PULL_REQUEST_BODY
  end

  # Returns the existing synchronization pull request when a retry already opened it.
  def existing_pull_request(client, token)
    entries = client.pull_requests.list_open \
      record,
      head: BRANCH_NAME,
      base: record.default_branch,
      token: token
    return if entries.empty?
    raise GithubClient::InvalidResponse, "GitHub returned duplicate workflow pull requests" if entries.many?

    validate_pull_request!(entries.first)
  end

  # Returns one validated Git commit identity from a reference response.
  def reference_sha(payload)
    sha = payload.fetch("object").fetch("sha")
    if !sha.is_a?(String) || !Build::COMMIT_SHA_FORMAT.match?(sha)
      raise GithubClient::InvalidResponse, "GitHub returned an invalid branch reference"
    end

    sha
  rescue KeyError, TypeError
    raise GithubClient::InvalidResponse, "GitHub returned an incomplete branch reference"
  end

  # Returns one validated Git blob identity from a Contents response.
  def content_sha(payload)
    sha = payload.fetch("sha")
    if !sha.is_a?(String) || !Build::COMMIT_SHA_FORMAT.match?(sha)
      raise GithubClient::InvalidResponse, "GitHub returned an invalid workflow identity"
    end

    sha
  end

  # Returns a pull request only when GitHub provides a valid identity and link.
  def validate_pull_request!(payload)
    number = payload.fetch("number")
    raise KeyError if !number.is_a?(Integer) || number <= 0

    url = payload.fetch("html_url")
    uri = URI.parse(url)
    github_uri = URI.parse(Rails.configuration.x.github_url)
    valid = uri.is_a?(URI::HTTPS) && uri.userinfo.nil? &&
      uri.host == github_uri.host && uri.port == github_uri.port
    raise GithubClient::InvalidResponse, "GitHub returned an invalid pull request URL" if !valid

    payload
  rescue KeyError, TypeError, URI::InvalidURIError
    raise GithubClient::InvalidResponse, "GitHub returned an incomplete pull request"
  end
end
