/** Names the viewer's timezone so Build times are unambiguous. */
export function formatBuildTime(timestamp: string) {
  return new Intl.DateTimeFormat("en", {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit",
    timeZoneName: "short",
  }).format(new Date(timestamp))
}
